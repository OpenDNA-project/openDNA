"""Regenerate app/enzyme_table.py: the commercially sold restriction enzymes, as facts (name, recognition site, cut offsets).
Needs Biopython (dev only; the app does not import it). Run the repo's .venv python on scripts/build_enzymes.py
Only the facts are taken (site, where each strand is cut); no file, comment or text of REBASE is copied. Enzymes with the same
site and cuts (isoschizomers) are listed once, under the name more suppliers sell (the 47 hand-written names win)."""
import sys
from pathlib import Path

from Bio.Restriction.Restriction_Dictionary import rest_dict

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "app"))
import enzymes  # noqa: E402

keep = {e[0]: e for e in enzymes.ENZYMES}      # the hand-written list stays first and unchanged (tests index into it)


def cuts_of(d):
    """((top, bottom), ...) from Biopython's first/second cut and overhang (the bottom cut is the top one minus the overhang)."""
    return tuple((c, c - d["ovhg"]) for c in (d["fst5"], d["scd5"]) if c is not None)


# Enzymes that cut only DNA that is methylated at their site (flagged, and hidden by the filters' default).
METHYL_DEPENDENT = {"DpnI", "MalI", "GlaI", "BisI", "BlsI"}

groups = {}   # (site, cuts) -> the names of every sold enzyme that reads and cuts like that (isoschizomers)
for name, d in sorted(rest_dict.items()):
    if not d["suppl"] or sum(c in "ACGT" for c in d["site"]) < 4 or d["fst5"] is None or d["substrat"] != "DNA" or not set(d["site"]) <= set("ACGTRYSWKMBDHVN"):
        continue                                # not sold, cut unknown, not a plain DNA site, or too short to be a sensible site (MspJI CNNR...)
    groups.setdefault((d["site"], cuts_of(d)), []).append(name)
for name, site, top, bottom in enzymes.ENZYMES:    # the conversion must reproduce the hand-written cuts
    assert (rest_dict[name]["site"], cuts_of(rest_dict[name])) == (site, ((top, bottom),)), name
    assert name in groups[(site, ((top, bottom),))], name
shown, aliases, methyl = {}, {}, set()   # name shown -> (site, cuts); name -> its other names
for kind, names in groups.items():
    pick = max(names, key=lambda n: (n in keep, len(rest_dict[n]["suppl"]), -len(n)))   # the hand-written name, else the most sold
    shown[pick] = kind
    if len(names) > 1:
        aliases[pick] = tuple(sorted(n for n in names if n != pick))
    if METHYL_DEPENDENT & set(names):
        methyl.add(pick)
new = sorted(n for n in shown if n not in keep)
lines = [f'    ("{n}", "{shown[n][0]}", {shown[n][1]!r}),' for n in new]
alias_lines = [f'    "{n}": {aliases[n]!r},' for n in sorted(aliases)]
NL = chr(10)
head = (
    '"""Generated by scripts/build_enzymes.py: commercially sold restriction enzymes beyond the hand-written list of enzymes.py.' + NL
    + 'MORE rows: name, recognition site (IUPAC), cuts ((top, bottom), ...) as in enzymes.Enzyme. ALIASES: the other names of an enzyme' + NL
    + '(isoschizomers: same site, same cuts), for every enzyme of the program. METHYLATED: those that cut only methylated DNA. Do not edit by hand."""' + NL)
body = ("MORE = [" + NL + NL.join(lines) + NL + "]" + NL + "ALIASES = {" + NL + NL.join(alias_lines) + NL + "}" + NL
        + f"METHYLATED = {tuple(sorted(methyl))!r}" + NL)
(ROOT / "app" / "enzyme_table.py").write_text(head + body, encoding="utf-8", newline=NL)
print(len(new), "enzymes added;", len(aliases), "with other names;", len(methyl), "methylation-dependent")
